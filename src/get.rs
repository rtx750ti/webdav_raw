//! HTTP GET 请求构建与发送。
//!
//! GET 取回一个资源的内容。本库只负责把请求发出去、把响应原样交回：状态码、
//! 响应头、响应体都不做判断，字节流怎么读由调用方决定。
//!
//! # 分片下载
//!
//! 按段取用 [`GetBuilder::range`](builder::GetBuilder::range)，它写 `Range`
//! 请求头，起止是闭区间。一个 Builder 构建一次请求，分几段、按什么顺序发、
//! 失败怎么重试由调用方决定，本库不维护分片状态。
//!
//! 服务端是否支持按段取，答案在响应里：支持时回 `206 Partial Content` 并带
//! `Content-Range`，忽略 `Range` 时回 `200` 加整份内容，两者本库都原样交出。

